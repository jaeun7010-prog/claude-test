/** 성씨 자리 글자에 SURNAME_ELEMENTS의 오행·확신을 입힌다. 표에 없는 글자는 사전 값 그대로 */
export function withSurnameElements<T extends HanjaChar>(chars: T[]): T[] {
  return chars.map((c) => {
    const e = SURNAME_ELEMENTS[c.hanja];
    return e ? { ...c, element: e[0], surnameConfidence: e[1] } : c;
  });
}
